const DICTS: Record<Lang, Record<string, string>> = { ru: {}, uz: UZ }

export function translate(lang: Lang, text: string, params?: Record<string, string | number>): string {
  const out = DICTS[lang]?.[text] ?? text
  if (!params) return out
  return out.replace(/\{(\w+)\}/g, (whole, key) => (key in params ? String(params[key]) : whole))
}

/** Подстановка без перевода — для сообщений сервера, которые уже на русском. */
export function fill(text: string, params?: Record<string, string | number>): string {
  return translate('ru', text, params)
}
